"""Build the editable, dependency-free shop from content/site.json."""
from pathlib import Path
from hashlib import sha256
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]
style_version = sha256((ROOT / 'assets/styles.css').read_bytes()).hexdigest()[:12]
data = json.loads((ROOT / 'content/site.json').read_text())
esc = html.escape
css = []
mobile_css = []

def font_scale(value, divisor):
    return re.sub(r'([\d.]+)px', lambda m: f'{float(m[1])/divisor:.6f}cqi', value)

def node_style(node, mode):
    p = node[mode]
    divisor = 12 if mode == 'desktop' else 3.9
    font_divisor = 12 if mode == 'desktop' else 3.2
    selector = '#' + node['id']
    layout = ';'.join(f'{key}:{p[source]/divisor:.6f}cqi' for key, source in [('left','x'),('top','y'),('width','width'),('height','height')])
    if node['kind'] == 'button':
        bottom = (p['y'] + p['height']) / divisor
        layout = f'left:{p["x"]/divisor:.6f}cqi;top:calc({bottom:.6f}cqi - var(--action-button-height));width:{p["width"]/divisor:.6f}cqi;height:var(--action-button-height)'
    result = selector + '{' + layout + '}'
    if node['kind'] == 'text':
        result += selector + ' .copy{' + f'font:{font_scale(p["font"],font_divisor)};letter-spacing:{font_scale(p["letterSpacing"],font_divisor)};text-align:{p["textAlign"]};text-transform:{p["textTransform"]};color:{p["color"]}' + '}'
    return result

def render_section(section):
    sid = section['id']
    section_label = {'preset-packages':'Photo presets','print-shop-gallery-to-darkroom':'Fine art prints','saltybabe-contact':'Get in touch','saltybabe-footer-1':'Footer'}[sid]
    css.append(f'#{sid} .canvas{{aspect-ratio:1200/{section["height"]}}}')
    mobile_css.append(f'#{sid} .canvas{{aspect-ratio:390/{section["mobileHeight"]}}}')
    output = [f'<section id="{sid}" aria-label="{section_label}"><div class="canvas">']
    for node in section['nodes']:
        css.append(node_style(node,'desktop'))
        mobile_css.append(node_style(node,'mobile'))
        attrs = f'id="{node["id"]}" class="element {node["kind"]}"'
        tag = 'a' if node['href'] else 'div'
        if node['href']:
            attrs += f' href="{esc(node["href"],quote=True)}"'
        if node['kind'] == 'image':
            label = node.get('alt','')
            if node['href'] and 'darkroom' in node['href']:
                label += ' — view print ' + node['href'].rsplit('/',1)[-1]
            inner = f'<img src="{esc(node["src"])}" alt="{esc(label)}" decoding="async">'
        elif node['kind'] == 'button':
            inner = f'<span class="button-label">{esc(node["text"])}</span>'
        elif node['kind'] == 'placeholder':
            attrs += f' role="img" aria-label="{esc(node["alt"])}"'
            inner = f'<span aria-hidden="true">{esc(node["text"])}</span>'
        elif node['kind'] == 'box':
            attrs += ' aria-hidden="true"'
            css.append(f'#{node["id"]}{{background:{node["background"]};border:{node["border"]};pointer-events:none}}')
            inner = ''
            tag = 'div'
        else:
            text_tag = 'h2' if sid=='preset-packages' and node['id'].endswith(('-0','-1')) else 'p'
            inner = f'<{text_tag} class="copy">'+esc(node['text']).replace('\n','<br>')+f'</{text_tag}>'
        output.append(f'<{tag} {attrs}>{inner}</{tag}>')
    output.append('</div></section>')
    return '\n'.join(output)

def render_navigation(on_product=False):
    links = []
    for item in data['navigation']:
        href = item['href']
        if on_product and href.startswith('#'):
            href = './' + href
        links.append(f'<a href="{esc(href)}">{esc(item["label"])}</a>')
    return ''.join(links)

social = ''.join(f'<a href="{esc(item["href"])}" aria-label="{label}">{item["svg"]}</a>' for item,label in zip(data['social'],['Instagram','Pinterest','TikTok']))
sections = {s['id']:render_section(s) for s in data['sections']}
layout = '/* Generated by scripts/build.py from the editable content file. */\n'+'\n'.join(css)+'\n@media(max-width:767px){\n'+'\n'.join(mobile_css)+'\n}\n'
layout_version = sha256(layout.encode()).hexdigest()[:12]
strip_photos = ''.join(f'<div class="gallery-photo"><img src="{esc(photo["src"])}" alt="{esc(photo["alt"])}" decoding="async"></div>' for photo in data['footerPhotos'])
strip = f'<div class="instagram-strip" role="group" aria-label="Photography collection"><div>{strip_photos}</div></div>'

def render_header(on_product=False):
    nav = render_navigation(on_product)
    return f'''<nav class="mobile-nav" aria-label="Mobile navigation">
<details class="mobile-menu">
<summary aria-label="Menu"><svg class="menu-icon" viewBox="0 0 50 32" aria-hidden="true"><path d="M0 1h50M0 16h50M0 31h50"></path></svg><span class="menu-label" aria-hidden="true">menu</span></summary>
<div class="mobile-menu-links">{nav}</div>
</details>
<a class="mobile-inquire" href="{esc(data['navigation'][-1]['href'])}">Inquire<svg viewBox="0 0 32 20" aria-hidden="true"><path d="M1 10h29M22 2l8 8-8 8"></path></svg></a>
</nav>
<header class="masthead">
<p class="tagline">underwater<br>photographer</p>
<a class="header-brand" href="./"><img class="brand-logo" src="assets/images/salty-babe-logo.png" alt="Salty Babe photo co. — Home" width="1158" height="555" decoding="async"></a>
<div class="social-links">{social}</div>
</header>
<nav class="site-nav" aria-label="Main navigation"><div>{nav}</div></nav>
'''

def render_page(title, description, main_content, on_product=False):
    product_styles = ''
    if on_product:
        version = sha256((ROOT / 'assets/products.css').read_bytes()).hexdigest()[:12]
        product_styles = f'<link rel="stylesheet" href="assets/products.css?v={version}">\n'
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow">
<meta name="description" content="{esc(description, quote=True)}">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; img-src 'self'; font-src 'self'; style-src 'self'; script-src 'self'; connect-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'self'; form-action 'none'">
<title>{esc(title)}</title>
<link rel="stylesheet" href="assets/fonts.css">
<link rel="stylesheet" href="assets/styles.css?v={style_version}">
<link rel="stylesheet" href="assets/layout.css?v={layout_version}">
{product_styles}</head>
<body>
<a class="skip-link" href="#main">Skip to shop</a>
{render_header(on_product)}<main id="main">
{main_content}
{strip}
</main>
<footer>{sections['saltybabe-footer-1']}</footer>
<script src="assets/mobile-menu.js" defer></script>
</body>
</html>
'''

home_content = f'''<section class="hero" aria-label="Shop and collection">
<picture>
<source media="(min-width:2000px)" srcset="assets/images/hero-desktop-wide-centered-photo.png">
<source media="(max-width:767px)" srcset="assets/images/hero-mobile-portrait-headroom.png">
<img class="hero-photo" src="assets/images/hero-desktop-centered-photo.png" alt="Snorkeler swimming with sharks in clear blue ocean water" fetchpriority="high">
</picture>
<img class="hero-wave" src="assets/images/hero-mobile-wave.png" alt="" aria-hidden="true">
<div class="hero-copy">
<h1>Dive In</h1>
<p>Shop &amp; Collection</p>
<a class="dive-arrow" href="#preset-packages" aria-label="Explore photo presets"><img src="assets/images/icons8-down-arrow-100_1.png" alt=""></a>
</div>
</section>
{sections['preset-packages']}
{sections['print-shop-gallery-to-darkroom']}
{sections['saltybabe-contact']}
<div class="social-spacer"></div>
'''
(ROOT/'index.html').write_text(render_page('Salty Babe Shop', 'Salty Babe photography shop recreation: ocean presets and fine art prints.', home_content.rstrip()))

products = json.loads((ROOT / 'content/products.json').read_text())
for product in products:
    photos = []
    for photo in product['photos']:
        size = 'wide' if photo['width'] > 500 else 'medium' if photo['width'] > 450 else 'standard'
        photos.append(f'<figure class="product-photo product-photo--{size}"><img src="{esc(photo["src"])}" alt="{esc(photo["alt"])}" width="{round(photo["width"])}" height="{round(photo["height"])}" decoding="async"></figure>')
    content = f'''<section class="product-detail" aria-labelledby="product-title">
<div class="product-gallery" role="group" aria-label="{esc(product['title'])} before and after photographs">{''.join(photos)}</div>
<div class="product-summary">
<h1 id="product-title">{esc(product['title'])}</h1>
<div class="product-description">{product['descriptionHtml']}</div>
<a class="element button product-buy" href="{esc(product['buyHref'])}"><span class="button-label">{esc(product['buyLabel'])}</span></a>
</div>
</section>'''
    if product['showContact']:
        content += '\n' + sections['saltybabe-contact'] + '\n<div class="social-spacer"></div>'
    (ROOT / (product['slug'] + '.html')).write_text(render_page(product['title'] + ' | Salty Babe', product['title'] + ': Lightroom presets for mobile and desktop.', content, on_product=True))

(ROOT/'assets/layout.css').write_text(layout)
print(f'Built the shop, {len(products)} product pages, and shared layout.css.')
